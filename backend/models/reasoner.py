class NeuroSymbolicReasoner:
    """
    Main reasoning engine combining GNN attention with LLM interpretation.
    
    This class orchestrates the complete explanation pipeline:
    1. Process GNN attention weights
    2. Map attention to chemical substructures
    3. Generate structured evidence
    4. Query LLM for scientific explanations
    5. Compile comprehensive report
    
    Usage:
        reasoner = NeuroSymbolicReasoner()
        report = reasoner.explain(
            smiles="c1ccc([N+](=O)[O-])cc1",
            attention_weights=attention_array,
            prediction_result=prediction
        )
    """
    
    # Tox21 endpoint names for reference
    TOX21_ENDPOINTS = [
        "NR-AR", "NR-AR-LBD", "NR-AhR", "NR-Aromatase", 
        "NR-ER", "NR-ER-LBD", "NR-PPAR-gamma",
        "SR-ARE", "SR-ATAD5", "SR-HSE", "SR-MMP", "SR-p53"
    ]
    
    def __init__(
        self, 
        llm_provider: Optional[LLMProvider] = None,
        use_mock: bool = False
    ):
        """
        Initialize the reasoner.
        
        Args:
            llm_provider: LLM provider instance (default: Groq)
            use_mock: If True, use mock LLM for testing
        """
        if use_mock:
            self.llm = MockLLMProvider()
            logger.info("Using Mock LLM provider for testing")
        elif llm_provider:
            self.llm = llm_provider
        else:
            self.llm = GroqLLMProvider()
        
        # Import substructure mapper
        try:
            from utils.substructure_mapper import SubstructureMapper
            self.substructure_mapper = SubstructureMapper()
            logger.info("Substructure mapper initialized")
        except ImportError:
            try:
                from substructure_mapper import SubstructureMapper
                self.substructure_mapper = SubstructureMapper()
            except ImportError:
                logger.warning("SubstructureMapper not available")
                self.substructure_mapper = None
        
        # RDKit for molecular properties
        try:
            from rdkit import Chem
            from rdkit.Chem import Descriptors, AllChem
            self.rdkit_available = True
        except ImportError:
            self.rdkit_available = False
            logger.warning("RDKit not available - molecular context limited")
    
    def _compute_molecular_context(self, smiles: str) -> MolecularContext:
        """Compute molecular properties for context."""
        context = MolecularContext(smiles=smiles)
        
        if not self.rdkit_available:
            return context
        
        from rdkit import Chem
        from rdkit.Chem import Descriptors, AllChem, rdMolDescriptors
        
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return context
        
        context.canonical_smiles = Chem.MolToSmiles(mol)
        context.molecular_formula = rdMolDescriptors.CalcMolFormula(mol)
        context.molecular_weight = Descriptors.MolWt(mol)
        context.num_atoms = mol.GetNumAtoms()
        context.num_heavy_atoms = Descriptors.HeavyAtomCount(mol)
        context.num_rings = rdMolDescriptors.CalcNumRings(mol)
        context.num_aromatic_rings = rdMolDescriptors.CalcNumAromaticRings(mol)
        context.logp = Descriptors.MolLogP(mol)
        context.tpsa = Descriptors.TPSA(mol)
        
        return context
    
    def _classify_risk_level(self, toxicity_prob: float) -> RiskLevel:
        """Classify risk level based on toxicity probability."""
        if toxicity_prob >= 0.9:
            return RiskLevel.CRITICAL
        elif toxicity_prob >= 0.7:
            return RiskLevel.HIGH
        elif toxicity_prob >= 0.4:
            return RiskLevel.MODERATE
        elif toxicity_prob >= 0.2:
            return RiskLevel.LOW
        else:
            return RiskLevel.MINIMAL
    
    def _extract_evidence(
        self,
        smiles: str,
        attention_weights: Any,
        threshold: float = 0.08
    ) -> Tuple[List[ToxicityEvidence], List[Dict]]:
        """
        Extract toxicity evidence from attention weights.
        
        Returns:
            Tuple of (toxicophore_evidence, critical_atoms)
        """
        import numpy as np
        attention_weights = np.array(attention_weights)
        
        toxicophores = []
        critical_atoms = []
        
        if self.substructure_mapper:
            # Get substructure matches
            matches = self.substructure_mapper.identify_substructures(
                smiles, attention_weights, threshold=threshold
            )
            
            for match in matches[:5]:  # Top 5
                evidence = ToxicityEvidence(
                    substructure_name=match.name.replace('_', ' ').title(),
                    smarts_pattern=match.smarts,
                    atom_indices=match.atoms,
                    attention_score=match.avg_attention,
                    toxicity_category=match.toxicity_category,
                    mechanism=match.mechanism,
                    confidence=min(1.0, match.avg_attention * 3)
                )
                toxicophores.append(evidence)
            
            # Get critical atoms
            atom_info = self.substructure_mapper.get_top_atoms(
                smiles, attention_weights, top_k=5
            )
            critical_atoms = atom_info
        
        return toxicophores, critical_atoms
    
    def _format_toxicophore_summary(self, evidence: List[ToxicityEvidence]) -> str:
        """Format toxicophores for prompt injection."""
        if not evidence:
            return "No known toxicophores identified with high confidence."
        
        lines = []
        for i, e in enumerate(evidence, 1):
            lines.append(
                f"{i}. **{e.substructure_name}** (atoms {e.atom_indices})\n"
                f"   - Attention Score: {e.attention_score:.1%}\n"
                f"   - Category: {e.toxicity_category}\n"
                f"   - Mechanism: {e.mechanism[:100]}..."
            )
        return "\n".join(lines)
    
    def _format_critical_atoms(self, atoms: List[Dict]) -> str:
        """Format critical atoms for prompt injection."""
        if not atoms:
            return "No critical atoms identified."
        
        lines = []
        for a in atoms:
            lines.append(
                f"- Atom {a['index']} ({a['symbol']}): "
                f"Attention {a['attention']:.1%}, "
                f"Aromatic: {a['is_aromatic']}, "
                f"Neighbors: {', '.join(a['neighbors'])}"
            )
        return "\n".join(lines)
    
    def _format_endpoint_predictions(
        self, 
        prediction: PredictionResult
    ) -> str:
        """Format endpoint predictions for prompt."""
        if not prediction.endpoint_scores:
            return f"Overall Toxicity: {prediction.overall_toxicity:.1%}"
        
        lines = [f"Overall Toxicity: {prediction.overall_toxicity:.1%}\n"]
        lines.append("Individual Endpoints:")
        
        # Sort by score
        sorted_endpoints = sorted(
            prediction.endpoint_scores.items(),
            key=lambda x: x[1],
            reverse=True
        )
        
        for name, score in sorted_endpoints:
            status = "⚠️ TOXIC" if score > 0.5 else "✓ Safe"
            lines.append(f"  - {name}: {score:.1%} {status}")
        
        return "\n".join(lines)
    
    def explain(
        self,
        smiles: str,
        attention_weights: Any,
        prediction_result: Optional[PredictionResult] = None,
        overall_toxicity: Optional[float] = None,
        endpoint_scores: Optional[Dict[str, float]] = None,
        generate_all_sections: bool = True
    ) -> ExplanationReport:
        """
        Generate a comprehensive explanation report.
        
        Args:
            smiles: SMILES string of the molecule
            attention_weights: Per-atom attention scores from GNN
            prediction_result: Structured prediction result (optional)
            overall_toxicity: Overall toxicity probability (if no PredictionResult)
            endpoint_scores: Individual endpoint scores (if no PredictionResult)
            generate_all_sections: If True, generate all explanation sections
            
        Returns:
            ExplanationReport with complete analysis
        """
        import numpy as np
        
        logger.info(f"Generating explanation for: {smiles[:50]}...")
        
        # Initialize report
        report = ExplanationReport(
            timestamp=datetime.now().isoformat(),
            smiles=smiles
        )
        
        # Compute molecular context
        report.molecular_context = self._compute_molecular_context(smiles)
        
        # Build prediction result if not provided
        if prediction_result is None:
            tox_prob = overall_toxicity or 0.5
            prediction_result = PredictionResult(
                overall_toxicity=tox_prob,
                endpoint_scores=endpoint_scores or {},
                risk_level=self._classify_risk_level(tox_prob)
            )
        
        report.prediction = prediction_result
        
        # Extract toxicity evidence from attention
        attention_weights = np.array(attention_weights)
        toxicophores, critical_atoms = self._extract_evidence(
            smiles, attention_weights
        )
        
        report.identified_toxicophores = toxicophores
        report.critical_atoms = critical_atoms
        
        # Calculate attention coverage (how much we can explain)
        explained_attention = sum(t.attention_score for t in toxicophores)
        report.attention_coverage = min(1.0, explained_attention)
        
        if not generate_all_sections:
            return report
        
        # ═══════════════════════════════════════════════════════════════════
        # Generate LLM Explanations
        # ═══════════════════════════════════════════════════════════════════
        
        # 1. Executive Summary
        summary_prompt = PromptTemplate.EXECUTIVE_SUMMARY.format(
            smiles=smiles,
            molecular_weight=report.molecular_context.molecular_weight,
            toxicity_probability=prediction_result.overall_toxicity,
            risk_level=prediction_result.risk_level.value,
            toxicophore_summary=self._format_toxicophore_summary(toxicophores),
            critical_atoms_summary=self._format_critical_atoms(critical_atoms)
        )
        
        report.executive_summary = self.llm.generate(
            summary_prompt,
            max_tokens=300,
            temperature=0.2
        )
        
        # 2. Detailed Mechanism
        mechanism_prompt = PromptTemplate.DETAILED_MECHANISM.format(
            smiles=smiles,
            toxicophore_details=self._format_toxicophore_summary(toxicophores),
            endpoint_predictions=self._format_endpoint_predictions(prediction_result)
        )
        
        report.detailed_mechanism = self.llm.generate(
            mechanism_prompt,
            max_tokens=800,
            temperature=0.3
        )
        
        # 3. Similar Compounds
        if toxicophores:
            toxicophore_list = "\n".join([
                f"- {t.substructure_name}: {t.mechanism[:80]}..."
                for t in toxicophores[:3]
            ])
            
            similar_prompt = PromptTemplate.SIMILAR_COMPOUNDS.format(
                smiles=smiles,
                toxicophore_list=toxicophore_list
            )
            
            similar_response = self.llm.generate(
                similar_prompt,
                max_tokens=500,
                temperature=0.3
            )
            
            # Parse similar compounds (simple extraction)
            report.similar_compounds = [
                line.strip() for line in similar_response.split('\n')
                if line.strip() and (line.strip()[0].isdigit() or line.strip().startswith('-'))
            ][:5]
        
        # 4. Safety Recommendations
        toxicophore_names = ", ".join([t.substructure_name for t in toxicophores[:3]]) or "None identified"
        
        safety_prompt = PromptTemplate.SAFETY_RECOMMENDATIONS.format(
            smiles=smiles,
            toxicity_probability=prediction_result.overall_toxicity,
            toxicophore_names=toxicophore_names,
            risk_level=prediction_result.risk_level.value
        )
        
        safety_response = self.llm.generate(
            safety_prompt,
            max_tokens=600,
            temperature=0.3
        )
        
        # Parse recommendations
        report.safety_recommendations = [
            line.strip() for line in safety_response.split('\n')
            if line.strip() and (line.strip()[0].isdigit() or line.strip().startswith('-'))
        ][:5]
        
        # Calculate overall confidence
        report.explanation_confidence = self._calculate_confidence(
            toxicophores, critical_atoms, prediction_result
        )
        
        logger.info(f"Explanation complete. Confidence: {report.explanation_confidence:.1%}")
        
        return report
    
    def _calculate_confidence(
        self,
        toxicophores: List[ToxicityEvidence],
        critical_atoms: List[Dict],
        prediction: PredictionResult
    ) -> float:
        """
        Calculate overall explanation confidence.
        Higher confidence when:
        - More known toxicophores identified
        - Higher attention on identified features
        - Clearer prediction (not near 0.5)
        """
        # Factor 1: Toxicophore coverage
        toxicophore_score = min(1.0, len(toxicophores) / 3)
        
        # Factor 2: Attention concentration
        if toxicophores:
            attention_score = sum(t.attention_score for t in toxicophores)
            attention_score = min(1.0, attention_score)
        else:
            attention_score = 0.3
        
        # Factor 3: Prediction clarity
        pred_clarity = abs(prediction.overall_toxicity - 0.5) * 2
        
        # Weighted average
        confidence = (
            0.4 * toxicophore_score +
            0.3 * attention_score +
            0.3 * pred_clarity
        )
        
        return min(1.0, max(0.0, confidence))
    
    def explain_batch(
        self,
        molecules: List[Dict],
        progress_callback: Optional[callable] = None
    ) -> List[ExplanationReport]:
        """
        Generate explanations for multiple molecules.
        
        Args:
            molecules: List of dicts with 'smiles', 'attention', 'prediction'
            progress_callback: Optional callback(i, total) for progress updates
            
        Returns:
            List of ExplanationReport objects
        """
        reports = []
        total = len(molecules)
        
        for i, mol_data in enumerate(molecules):
            if progress_callback:
                progress_callback(i, total)
            
            report = self.explain(
                smiles=mol_data['smiles'],
                attention_weights=mol_data['attention'],
                overall_toxicity=mol_data.get('prediction'),
                endpoint_scores=mol_data.get('endpoint_scores')
            )
            reports.append(report)
        
        return reports


