class RiskLevel(Enum):
    """Toxicity risk classification levels."""
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MODERATE = "MODERATE"
    LOW = "LOW"
    MINIMAL = "MINIMAL"


@dataclass
class ToxicityEvidence:
    """
    Structured evidence supporting a toxicity prediction.
    Used for building interpretable explanations.
    """
    substructure_name: str
    smarts_pattern: str
    atom_indices: List[int]
    attention_score: float  # 0-1, from GNN
    toxicity_category: str
    mechanism: str
    confidence: float = 0.0


@dataclass
class MolecularContext:
    """
    Complete molecular context for LLM reasoning.
    Contains all information needed to generate explanations.
    """
    smiles: str
    canonical_smiles: str = ""
    molecular_formula: str = ""
    molecular_weight: float = 0.0
    num_atoms: int = 0
    num_heavy_atoms: int = 0
    num_rings: int = 0
    num_aromatic_rings: int = 0
    logp: float = 0.0
    tpsa: float = 0.0  # Topological Polar Surface Area


@dataclass 
class PredictionResult:
    """
    Complete prediction result with all endpoint scores.
    """
    overall_toxicity: float  # 0-1 probability
    endpoint_scores: Dict[str, float] = field(default_factory=dict)
    risk_level: RiskLevel = RiskLevel.MODERATE
    toxic_endpoints: List[str] = field(default_factory=list)
    safe_endpoints: List[str] = field(default_factory=list)


@dataclass
class ExplanationReport:
    """
    Complete explanation report generated by the reasoner.
    This is the final output for end users and paper figures.
    """
    # Input (required - no defaults)
    smiles: str
    timestamp: str
    
    # Optional with defaults
    model_version: str = "DeNovo-XAI v1.0"
    molecular_context: Optional[MolecularContext] = None
    
    # Predictions
    prediction: Optional[PredictionResult] = None
    
    # Evidence
    identified_toxicophores: List[ToxicityEvidence] = field(default_factory=list)
    critical_atoms: List[Dict] = field(default_factory=list)
    
    # LLM-generated explanations
    executive_summary: str = ""
    detailed_mechanism: str = ""
    similar_compounds: List[str] = field(default_factory=list)
    safety_recommendations: List[str] = field(default_factory=list)
    
    # Confidence metrics
    explanation_confidence: float = 0.0
    attention_coverage: float = 0.0  # How much attention is explained by known patterns
    
    def to_dict(self) -> Dict:
        """Convert to dictionary for JSON serialization."""
        return asdict(self)
    
    def to_json(self) -> str:
        """Convert to formatted JSON string."""
        return json.dumps(self.to_dict(), indent=2, default=str)


