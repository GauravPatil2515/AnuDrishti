def create_reasoner(
    use_groq: bool = True,
    api_key: Optional[str] = None,
    use_mock: bool = False
) -> NeuroSymbolicReasoner:
    """
    Factory function to create a configured reasoner.
    
    Args:
        use_groq: If True, use Groq LLM (default)
        api_key: Optional API key override
        use_mock: If True, use mock LLM for testing
        
    Returns:
        Configured NeuroSymbolicReasoner instance
    """
    if use_mock:
        return NeuroSymbolicReasoner(use_mock=True)
    elif use_groq:
        provider = GroqLLMProvider(api_key=api_key)
        return NeuroSymbolicReasoner(llm_provider=provider)
    else:
        return NeuroSymbolicReasoner(use_mock=True)


