class LLMProvider(ABC):
    """Abstract base class for LLM providers."""
    
    @abstractmethod
    def generate(self, prompt: str, max_tokens: int = 1000, temperature: float = 0.3) -> str:
        """Generate text completion from prompt."""
        pass
    
    @abstractmethod
    def is_available(self) -> bool:
        """Check if the LLM provider is available."""
        pass


class GroqLLMProvider(LLMProvider):
    """
    Groq LLM provider for high-speed inference.
    Uses LLaMA 3.3 70B for scientific reasoning.
    """
    
    MODEL_ID = "llama-3.3-70b-versatile"
    
    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or os.getenv('GROQ_API_KEY')
        self._client = None
        self._initialize_client()
    
    def _initialize_client(self):
        """Initialize the Groq client."""
        if not self.api_key:
            logger.warning("GROQ_API_KEY not found. LLM reasoning will be disabled.")
            return
        
        try:
            from groq import Groq
            self._client = Groq(api_key=self.api_key)
            logger.info(f"Groq client initialized with model: {self.MODEL_ID}")
        except ImportError:
            logger.error("groq package not installed. Run: pip install groq")
        except Exception as e:
            logger.error(f"Failed to initialize Groq client: {e}")
    
    def is_available(self) -> bool:
        return self._client is not None
    
    def generate(
        self, 
        prompt: str, 
        max_tokens: int = 1500,
        temperature: float = 0.3,
        system_prompt: Optional[str] = None
    ) -> str:
        """
        Generate completion using Groq LLaMA 3.3.
        
        Args:
            prompt: User prompt
            max_tokens: Maximum tokens in response
            temperature: Sampling temperature (lower = more deterministic)
            system_prompt: Optional system prompt
            
        Returns:
            Generated text response
        """
        if not self.is_available():
            return "[LLM reasoning unavailable - API key not configured]"
        
        try:
            messages = []
            
            if system_prompt:
                messages.append({
                    "role": "system",
                    "content": system_prompt
                })
            
            messages.append({
                "role": "user", 
                "content": prompt
            })
            
            response = self._client.chat.completions.create(
                model=self.MODEL_ID,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                top_p=0.9
            )
            
            return response.choices[0].message.content.strip()
            
        except Exception as e:
            logger.error(f"Groq API error: {e}")
            return f"[LLM reasoning failed: {str(e)}]"


